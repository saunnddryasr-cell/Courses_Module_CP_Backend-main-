CREATE TABLE IF NOT EXISTS sources (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key              TEXT UNIQUE NOT NULL,
    category                TEXT NOT NULL,
    type                    TEXT NOT NULL CHECK (type IN ('api', 'rss', 'scrape', 'manual')),
    base_url                TEXT,
    auth_config             TEXT,
    field_mapping           JSONB NOT NULL DEFAULT '{}'::jsonb,
    poll_frequency_minutes  INTEGER NOT NULL DEFAULT 240 CHECK (poll_frequency_minutes > 0),
    enabled                 BOOLEAN NOT NULL DEFAULT FALSE,
    last_run_at             TIMESTAMPTZ,
    last_success_at         TIMESTAMPTZ,
    consecutive_failures    INTEGER NOT NULL DEFAULT 0,
    last_error              TEXT,
    last_alerted_at         TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS source_runs (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       INTEGER NOT NULL REFERENCES sources(id),
    started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ,
    status          TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'succeeded', 'failed')),
    records_fetched INTEGER NOT NULL DEFAULT 0,
    records_inserted INTEGER NOT NULL DEFAULT 0,
    error_message   TEXT
);

CREATE INDEX IF NOT EXISTS idx_source_runs_source_started ON source_runs(source_id, started_at DESC);

CREATE TABLE IF NOT EXISTS raw_records (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       INTEGER NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    category        TEXT NOT NULL,
    title           TEXT NOT NULL,
    org             TEXT,
    description     TEXT,
    deadline        DATE,
    link            TEXT NOT NULL,
    location        TEXT,
    eligibility     TEXT,
    tags            TEXT[] NOT NULL DEFAULT '{}',
    content_hash    TEXT NOT NULL,
    scraped_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_id, content_hash)
);

CREATE INDEX IF NOT EXISTS idx_raw_records_category ON raw_records(category);
CREATE INDEX IF NOT EXISTS idx_raw_records_scraped_at ON raw_records(scraped_at DESC);

CREATE TABLE IF NOT EXISTS formatted_posts (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_record_id   INTEGER NOT NULL REFERENCES raw_records(id) ON DELETE CASCADE,
    platform        TEXT NOT NULL CHECK (platform IN ('whatsapp', 'telegram', 'community')),
    body_text       TEXT NOT NULL,
    status          TEXT NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'approved', 'rejected', 'published')),
    edited_by       TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at     TIMESTAMPTZ,
    reviewed_by     TEXT,
    publication_error TEXT,
    UNIQUE (raw_record_id, platform)
);

CREATE INDEX IF NOT EXISTS idx_formatted_posts_status ON formatted_posts(status);
ALTER TABLE formatted_posts ADD COLUMN IF NOT EXISTS publication_error TEXT;

CREATE TABLE IF NOT EXISTS publish_log (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formatted_post_id   INTEGER NOT NULL REFERENCES formatted_posts(id),
    platform            TEXT NOT NULL,
    published_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_by        TEXT,
    channel_id           TEXT,
    UNIQUE (formatted_post_id)
);

ALTER TABLE sources ADD COLUMN IF NOT EXISTS last_error TEXT;
ALTER TABLE sources ADD COLUMN IF NOT EXISTS last_alerted_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS category_publish_settings (
    category            TEXT PRIMARY KEY,
    publish_mode        TEXT NOT NULL DEFAULT 'manual_approval'
                        CHECK (publish_mode IN ('manual_approval', 'auto_publish')),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          TEXT
);
